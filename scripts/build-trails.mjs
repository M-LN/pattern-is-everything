const S_START = '  <!-- trails:start -->', S_END = '  <!-- trails:end -->';
function sitemapBlock(xml) {
  // Keep each URL's lastmod unless its page changed; the caller decides.
  const urls = [`${SITE}/trails/`, ...trails.map(t => `${SITE}/trails/${t.id}/`)];
  return [S_START, ...urls.map(u =>
    `  <url>\n    <loc>${u}</loc>\n    <priority>0.7</priority>\n    <lastmod>${new Date().toISOString().slice(0, 10)}</lastmod>\n  </url>`), S_END].join('\n');
}

/* Write `file` if its content (ignoring line endings) changed. In --check
   mode, report instead. Keeps the file's own line endings. */
let stale = 0, written = 0;
async function sync(file, next, label = file, compare = s => s) {
  const abs = join(ROOT, file);
  const cur = existsSync(abs) ? await readFile(abs, 'utf8') : null;
  if (cur !== null && compare(lf(cur)) === compare(lf(next))) return;
  if (CHECK) { stale++; console.log(`  stale: ${label}`); return; }
  const eol = cur && cur.includes('\r\n') ? '\r\n' : '\n';
  await mkdir(dirname(abs), { recursive: true });
  await writeFile(abs, lf(next).replace(/\n/g, eol));
  written++;
}

/* A synced folder (OneDrive) can briefly lock a file it is uploading, and
   rewriting it then fails with EBUSY/EPERM/UNKNOWN. A short retry rides that out. */
async function put(file, data) {
  await mkdir(dirname(file), { recursive: true });
  for (let attempt = 1; ; attempt++) {
    try { return await writeFile(file, data); }
    catch (e) {
      if (attempt >= 6 || !['EBUSY', 'EPERM', 'EACCES', 'UNKNOWN'].includes(e.code)) throw e;
      await new Promise(r => setTimeout(r, 500 * attempt));
    }
  }
}

async function buildCards(only) {
  const { serve, launch, connect } = await import('./chrome.mjs');
  const server = await serve(ROOT);
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await launch();
  try {
    const card = await connect(browser.port);
    await card.send('Page.enable');
    await card.send('Emulation.setDeviceMetricsOverride', { width: 1200, height: 630, deviceScaleFactor: 1, mobile: false });
    await card.send('Page.bringToFront');
    await card.goto(`${base}/scripts/og-card.html`);
    for (const trail of only) {
      // The stop whose visualization shows the most — the largest thumbnail,
      // since a near-empty picture compresses to almost nothing.
      const thumbFile = trail.stops
        .map(s => join(ROOT, 'assets', 'thumbs', `${s.key.slice(1).replace('/#', '/')}.webp`))
        .filter(f => existsSync(f))
        .sort((a, b) => readFileSync(b).length - readFileSync(a).length)[0];
      const src = thumbFile ? `data:image/webp;base64,${readFileSync(thumbFile).toString('base64')}` : '';
      const f = JSON.stringify({ collection: `Pattern trail · ${trail.stops.length} stops`, title: trail.title,
        pattern: collectionsOf(trail).join(' → '), src });
      await card.evaluate(`(async () => {
        const f = ${f};
        document.querySelector('.col').textContent = 'Pattern is Everything · ' + f.collection;
        document.querySelector('.title').textContent = f.title;
        document.querySelector('.pattern').textContent = f.pattern;
        document.body.classList.toggle('no-viz', !f.src);
        const img = document.querySelector('.viz img');
        img.src = f.src;
        if (f.src) await img.decode();
        document.body.classList.toggle('side', !!f.src && img.naturalWidth / img.naturalHeight < 2.2);
        await document.fonts.ready;
        return true;
      })()`);
      const shot = Buffer.from((await card.send('Page.captureScreenshot', { format: 'jpeg', quality: 86 })).data, 'base64');
      await put(cardPath(trail), shot);
      console.log(`assets/og/trails/${trail.id}.jpg`);
    }
    card.close();
  } finally {
    server.close();
    await browser.close();
  }
}

async function run() {
  if (!CHECK) {
    const need = trails.filter(t => CARDS || !existsSync(cardPath(t)));
    if (need.length) await buildCards(need);
  }
  await sync('trails/index.html', indexPage());
  for (const t of trails) await sync(`trails/${t.id}/index.html`, trailPage(t));

  const home = await readFile(join(ROOT, 'index.html'), 'utf8');
  if (!home.includes(H_START)) throw new Error(`index.html has no ${H_START} marker`);
  await sync('index.html', home.replace(new RegExp(`${H_START}[\\s\\S]*?${H_END}`), homeBlock()), 'index.html trails block');

  const xml = lf(await readFile(join(ROOT, 'sitemap.xml'), 'utf8'));
  const block = sitemapBlock(xml);
  const nextXml = xml.includes(S_START)
    ? xml.replace(new RegExp(`${S_START}[\\s\\S]*?${S_END}`), block)
    : xml.replace('</urlset>', `${block}\n</urlset>`);
  // A date bump alone is not drift.
  await sync('sitemap.xml', nextXml, 'sitemap.xml trails block', s => s.replace(/<lastmod>[^<]*<\/lastmod>/g, ''));

  if (CHECK) {
    if (stale) { console.error(`${stale} trail file(s) out of date — run: node scripts/build-trails.mjs`); process.exit(1); }
    console.log(`trails: ${trails.length} trails, all generated files current`);
  } else {
    console.log(`trails: ${trails.length} trails, ${written} file(s) written`);
  }
}

run().catch(e => { console.error(e); process.exit(1); });
