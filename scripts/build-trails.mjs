/* ── Pattern trails ──
   A trail follows one pattern across collections — the bell curve from the
   CLT to Bollinger Bands to tail risk — as a numbered route with a note on
   why each stop belongs. The site's argument is that patterns recur across
   fields; until now a visitor had to discover that alone.

   Source: trails/trails.json (hand-edited). This writes, from it and
   connections.json:
     /trails/index.html          all trails
     /trails/<id>/index.html     one trail: intro, stops, outro
     index.html                  the homepage's "Pattern trails" block
     sitemap.xml                 the trail pages
     assets/og/trails/<id>.jpg   share cards (with --cards, or when missing;
                                 needs Chrome, via scripts/chrome.mjs)

   Stops link into the collection readers with ?trail=<id>, where
   js/trails.js shows the stop's note and the way on.

   Usage:  node scripts/build-trails.mjs [--cards]
           node scripts/build-trails.mjs --check   (drift only; exits 1) */
import { readFileSync, existsSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://patterniseverything.com';
const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const CARDS = args.includes('--cards');

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const hash8 = file => createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 8);
const lf = s => s.replace(/\r\n/g, '\n');

const { trails } = JSON.parse(readFileSync(join(ROOT, 'trails', 'trails.json'), 'utf8'));
const { topics } = JSON.parse(readFileSync(join(ROOT, 'connections.json'), 'utf8'));

/* Every stop must be a real topic; a typo would ship a dead link. */
const problems = [];
const ids = new Set();
for (const t of trails) {
  if (!/^[a-z0-9-]+$/.test(t.id) || ids.has(t.id)) problems.push(`trail id "${t.id}" is missing, malformed or repeated`);
  ids.add(t.id);
  if (!t.stops || t.stops.length < 3) problems.push(`${t.id}: a trail needs at least 3 stops`);
  for (const s of t.stops || []) if (!topics[s.key]) problems.push(`${t.id}: no topic ${s.key}`);
}
if (problems.length) { console.error(problems.map(p => '  ✗ ' + p).join('\n')); process.exit(1); }

/* "/stats/#clt-sampling" → the reader URL that opens it on this trail. */
const stopUrl = (trail, key) => { const [p, id] = key.split('#'); return `${p}?trail=${trail.id}#${id}`; };
const thumbOf = key => {
  const t = topics[key];
  return t.i ? `/assets/thumbs/${key.slice(1).replace('/#', '/')}.webp?v=${t.i}` : null;
};
const collectionsOf = trail => [...new Set(trail.stops.map(s => topics[s.key].c))];
const cardPath = trail => join(ROOT, 'assets', 'og', 'trails', `${trail.id}.jpg`);
const ogImageOf = trail => existsSync(cardPath(trail))
  ? `${SITE}/assets/og/trails/${trail.id}.jpg?v=${hash8(cardPath(trail))}`
  : `${SITE}/assets/og/og-start.png`;

/* A trail as a card: the homepage block and the /trails/ index share it. */
function trailCard(trail) {
  const strip = trail.stops.slice(0, 4).map(s => thumbOf(s.key)).filter(Boolean)
    .map(src => `<img src="${esc(src)}" alt="" loading="lazy" decoding="async">`).join('');
  return `<a class="trail-card" href="/trails/${trail.id}/" data-trail="${trail.id}">
      <div class="trail-card-strip" aria-hidden="true">${strip}</div>
      <div class="trail-card-body">
        <div class="trail-card-kicker">${trail.stops.length} stops · ${esc(collectionsOf(trail).join(' · '))}</div>
        <div class="trail-card-title">${esc(trail.title)}</div>
        <p class="trail-card-intro">${esc(trail.intro)}</p>
        <div class="trail-card-foot"><span class="trail-card-progress" data-trail-progress="${trail.id}"></span><span class="trail-card-go">Follow the trail →</span></div>
      </div>
    </a>`;
}

