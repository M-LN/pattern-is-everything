/* ── Topic images: preview thumbnails and share cards ──
   Opens every pre-rendered topic page in headless Chrome (or Edge), in the
   dark theme, captures its visualization, and writes two images:

   1. assets/thumbs/<collection>/<id>.webp — 480px, for the preview card
      shown when hovering a link to the topic (js/connections.js).
   2. assets/og/topics/<collection>/<id>.jpg — the 1200×630 share card
      (og:image / twitter:image on the topic's pre-rendered page): collection,
      title, the topic's pattern line and its visualization, laid out by
      scripts/og-card.html in the site's own fonts. Before these, a shared
      topic showed its collection's generic card, or the site's.

   Some visualizations open on an empty starting state and only fill in once
   played; when a capture comes out nearly blank, the play control is pressed
   and the fuller capture kept.

   No dependencies: scripts/chrome.mjs drives any installed Chrome over the
   DevTools protocol.

   Usage:  node scripts/build-topic-images.mjs [collection ...]   (default: all)
   Then:   node scripts/prerender.mjs <collections>   — points og:image at the
             cards, versioned by their hash
           node scripts/build.mjs   — records the thumbnails' hashes in
             connections.json */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve, launch, connect, sleep } from './chrome.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COLLECTIONS = ['stats', 'ml-math', 'llm', 'mlops', 'timeseries', 'essays',
  'markets/charts', 'markets/indicators', 'markets/psychology', 'markets/risk'];
const THUMB_WIDTH = 480;     // output pixels; the card shows it at ~300 CSS px
const SETTLE_MS = 700;       // let the first draw (and any intro animation) land
const LOW_DETAIL = 2500;     // bytes: a thumbnail this small is nearly blank
const PLAY_MS = 2500;        // how long a pressed play button gets to run
const DPR = 2;               // canvases draw at 2x, so the share card's copy is sharp
const TOPIC_TIMEOUT_MS = 60000;

/* The repo can live in a synced folder (OneDrive here), whose client briefly
   locks files it is uploading — rewriting one then fails with EBUSY/EPERM.
   A short retry rides that out. */
async function put(file, data) {
  await mkdir(dirname(file), { recursive: true });
  for (let attempt = 1; ; attempt++) {
    try { return await writeFile(file, data); }
    catch (e) {
      if (attempt >= 6 || !['EBUSY', 'EPERM', 'EACCES', 'UNKNOWN'].includes(e.code)) throw e;
      await sleep(500 * attempt);
    }
  }
}

/* Share-card accent per world, brightened a little for the dark ground. */
const accentFor = col => col.startsWith('markets/') ? '#3fa37e' : col === 'essays' ? '#a86fc4' : '#d0573a';

async function run() {
  const only = process.argv.slice(2);
  const cols = only.length ? only : COLLECTIONS;
  const server = await serve(ROOT);
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await launch();
  let made = 0, replayed = 0;
  const skipped = [];
  try {
    // Two tabs: one walks the topic pages, the other holds the card template.
    const page = await connect(browser.port);
    const card = await connect(browser.port);
    for (const tab of [page, card]) {
      await tab.send('Page.enable');
      // Dark theme: the pages read it on load.
      await tab.send('Page.addScriptToEvaluateOnNewDocument', { source: "try{localStorage.setItem('theme','dark')}catch(e){}" });
      await tab.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: 'dark' }] });
    }
    await page.send('Emulation.setDeviceMetricsOverride', { width: 1100, height: 900, deviceScaleFactor: DPR, mobile: false });
    await card.send('Emulation.setDeviceMetricsOverride', { width: 1200, height: 630, deviceScaleFactor: 1, mobile: false });
    /* Only the tab in front renders: a background tab's screenshots and image
       decodes wait for a frame that never comes, which stalled whole runs.
       So each tab is brought forward before it's used. */
    await card.send('Page.bringToFront');
    await card.goto(`${base}/scripts/og-card.html`);
    await card.evaluate('document.fonts.ready.then(() => true)');

    for (const col of cols) {
      const ids = (await readdir(join(ROOT, col), { withFileTypes: true }))
        .filter(d => d.isDirectory() && existsSync(join(ROOT, col, d.name, 'index.html'))).map(d => d.name);
      for (const id of ids) {
        const html = await readFile(join(ROOT, col, id, 'index.html'), 'utf8');
        if (!html.includes('Generated by scripts/prerender.mjs')) continue;
        /* One topic, with a deadline: a page that never settles fails the run
           with its name instead of hanging it. */
        const one = async () => {
          await page.send('Page.bringToFront');
          await page.goto(`${base}/${col}/${id}/`);
          await sleep(SETTLE_MS);
          const info = await page.evaluate(`(() => {
            const topic = document.querySelector('.topic');
            const h = topic.querySelector('.topic-meta h2');
            const title = h ? [...h.childNodes].filter(n => !(n.classList && n.classList.contains('heading-anchor')))
              .map(n => n.textContent).join('').trim() : document.title.split(' — ')[0];
            const pt = topic.querySelector('.pt-text');
            const c = topic.querySelector('.va canvas') || topic.querySelector('canvas');
            let box = null;
            if (c) {
              c.scrollIntoView({ block: 'center' });
              const r = c.getBoundingClientRect();
              if (r.width && r.height) box = { x: r.left + scrollX, y: r.top + scrollY, w: r.width, h: r.height };
            }
            return { title, pattern: pt ? pt.textContent.trim() : '',
                     collection: document.title.split(' — ').slice(1).join(' — '), box };
          })()`);
          const { box } = info;
          let vizPng = null;
          if (box) {
            await sleep(120);
            const clip = scale => ({ x: box.x, y: box.y, width: box.w, height: box.h, scale });
            const shoot = async (format, scale, quality) => Buffer.from((await page.send('Page.captureScreenshot',
              { format, quality, clip: clip(scale) })).data, 'base64');
            // At DPR 2 a clip renders 2 pixels per CSS pixel; scale down to the thumb width.
            const thumbShot = () => shoot('webp', THUMB_WIDTH / (box.w * DPR), 78);
            let thumb = await thumbShot();
            if (thumb.length < LOW_DETAIL) {
              const pressed = await page.evaluate(`(() => {
                // A play-type button if there is one, else the first control that
                // isn't a reset (SGD / Momentum / Adam and the like).
                const all = [...document.querySelectorAll('.topic .va button, .topic button.btn')];
                const b = all.find(b => /animat|run|play|start|drop|simulat|train|step|go\\b/i.test(b.textContent))
                  || all.find(b => !/reset|clear|↺/i.test(b.textContent));
                if (!b) return false;
                b.click();
                return true;
              })()`);
              if (pressed) {
                await sleep(PLAY_MS);
                const played = await thumbShot();
                if (played.length > thumb.length) { thumb = played; replayed++; }
              }
            }
            const tOut = join(ROOT, 'assets', 'thumbs', col, `${id}.webp`);
            await put(tOut, thumb);
            vizPng = await shoot('png', 1);
          } else {
            skipped.push(`${col}/${id}`);
          }

          // Lay out the share card and capture it.
          await card.send('Page.bringToFront');
          const fields = JSON.stringify({ ...info, accent: accentFor(col),
            src: vizPng ? `data:image/png;base64,${vizPng.toString('base64')}` : '' });
          await card.evaluate(`(async () => {
            const f = ${fields};
            document.documentElement.style.setProperty('--accent', f.accent);
            document.querySelector('.col').textContent = 'Pattern is Everything · ' + f.collection;
            document.querySelector('.title').textContent = f.title;
            document.querySelector('.pattern').textContent = f.pattern;
            document.querySelector('.pattern').hidden = !f.pattern;
            document.body.classList.toggle('no-viz', !f.src);
            const img = document.querySelector('.viz img');
            img.src = f.src || '';
            if (f.src) await img.decode();
          // Squarer visualizations go beside the text (og-card.html).
          document.body.classList.toggle('side', !!f.src && img.naturalWidth / img.naturalHeight < 2.2);
            await document.fonts.ready;
            return true;
          })()`);
          const shot = Buffer.from((await card.send('Page.captureScreenshot', { format: 'jpeg', quality: 86 })).data, 'base64');
          const oOut = join(ROOT, 'assets', 'og', 'topics', col, `${id}.jpg`);
          await put(oOut, shot);
          made++;
          return true;
        };
        let timer;
        const deadline = new Promise(r => { timer = setTimeout(() => r(false), TOPIC_TIMEOUT_MS); });
        const done = await Promise.race([one(), deadline]);
        clearTimeout(timer);
        if (!done) throw new Error(`${col}/${id} did not finish within ${TOPIC_TIMEOUT_MS / 1000}s`);
      }
      console.log(`${col}: done`);
    }
    page.close(); card.close();
  } finally {
    server.close();
    await browser.close();
  }
  console.log(`${made} topics: share cards in assets/og/topics/, thumbnails in assets/thumbs/ ` +
    `(${replayed} after pressing play)` + (skipped.length ? `; no canvas, so no thumbnail: ${skipped.join(', ')}` : ''));
  console.log('Now run: node scripts/prerender.mjs <collections>, then node scripts/build.mjs');
}

run().catch(e => { console.error(e); process.exit(1); });
